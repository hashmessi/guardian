"""Domain types, enumerations, and dataclasses for Process Guardian."""

from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, Any, Optional


class RegimeType(str, Enum):
    """The 9 baseline operational regimes supported by the simulator."""
    HEALTHY = "healthy"
    THERMAL_DRIFT = "thermal_drift"
    PRESSURE_DRIFT = "pressure_drift"
    MOISTURE_DRIFT = "moisture_drift"
    CYCLE_INSTABILITY = "cycle_instability"
    COMBINED_DRIFT = "combined_drift"
    SENSOR_NOISE = "sensor_noise"
    RECOVERY = "recovery"
    UNSEEN_DRIFT = "unseen_drift"


@dataclass
class MachineContext:
    """Production context attached to machines and cycles."""
    machine_id: str = "IMM-01"
    mold_id: str = "MOLD-HOUSING-04"
    part_id: str = "PART-AUTO-HOUSING-A"
    recipe_id: str = "RECIPE-PP-V2.1"
    recipe_version: str = "2.1"
    material_batch: str = "BATCH-20260924-A"
    operator_id: str = "OP-102"


@dataclass
class RawCycleTelemetry:
    """Cycle-level summary telemetry record generated by the simulator."""
    cycle_index: int
    # Barrel temperatures (°C)
    barrel_temp_z1: float
    barrel_temp_z2: float
    barrel_temp_z3: float
    barrel_temp_z4: float
    barrel_temp_z5: float
    nozzle_temp: float
    # Pressures (bar)
    injection_pressure: float
    peak_pressure: float
    hold_pressure: float
    # Timings (seconds)
    injection_time: float
    hold_time: float
    cooling_time: float
    cycle_time: float
    # Material & Quality outcomes
    part_weight: float
    material_moisture: float
    ambient_temp: float
    ambient_humidity: float
    # Quality inspection ground truth
    sink_mark_depth: float = 0.0
    flash_observed: bool = False
    defect_flag: bool = False
    # Meta
    regime: str = "healthy"
    timestamp_offset_s: float = 0.0
    extra: Dict[str, Any] = field(default_factory=dict)
